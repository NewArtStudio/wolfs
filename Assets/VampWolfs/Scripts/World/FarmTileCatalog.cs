using System;
using System.Collections.Generic;
using UnityEngine;

namespace VampWolfs
{
    /// <summary>One piece of a tile (barn, fence, tree, road…). Coordinates are local to the tile (-9..9 m).</summary>
    [Serializable]
    public class FarmPieceDef
    {
        public string T;      // type ("barn", "fence", "road"…)
        public float X, Z;    // center, meters (x = east, z = north)
        public float R;       // yaw in degrees (same as Unity)
        public float L, W;    // length / width (fences, roads, crop rows, pond)
        public float S;       // scale (0 = 1)
        public string E;      // roads only: tile side it connects ("n","e","s","w"), "" = middle part

        public float Scale { get { return S > 0f ? S : 1f; } }
    }

    /// <summary>Collision shape of a piece type (written by build_farm_tiles.py: one source of truth).</summary>
    [Serializable]
    public class FarmShapeDef
    {
        public string T;
        public string Shape;  // "box", "circle", "ellipse"
        public float W, D;    // box: width x depth; circle: W = radius. 0 = comes from the piece (W, L)
        public bool Block;    // blocks movement and projectiles
    }

    [Serializable]
    public class FarmTileDef
    {
        public string Id;
        public string Name;
        public float Weight;  // chance relative to the others
        public int Max;       // most copies in one map (0 = no limit)
        public FarmPieceDef[] Pieces;
    }

    /// <summary>
    /// The farm tiles (Resources/VampWolfs/farm_tiles.json, generated by Tools/Data/build_farm_tiles.py).
    /// Every tile keeps its border free, so any tile fits next to any other in any rotation.
    /// </summary>
    [Serializable]
    public class FarmTileCatalog
    {
        public float TileSize = 18f;
        public float Margin = 2f;
        public FarmShapeDef[] Shapes;
        public FarmTileDef[] Tiles;

        [NonSerialized] Dictionary<string, FarmShapeDef> shapeMap;
        [NonSerialized] bool loaded;

        static FarmTileCatalog instance;

        public static FarmTileCatalog Instance
        {
            get
            {
                if (instance == null)
                {
                    instance = Load();
                }
                return instance;
            }
        }

        public bool IsLoaded { get { return loaded; } }

        static FarmTileCatalog Load()
        {
            FarmTileCatalog c = null;
            TextAsset json = Resources.Load<TextAsset>("VampWolfs/farm_tiles");
            if (json != null)
            {
                try { c = JsonUtility.FromJson<FarmTileCatalog>(json.text); }
                catch (Exception e) { Debug.LogError("[VampWolfs] farm_tiles.json inválido: " + e.Message); }
            }
            if (c == null || c.Tiles == null || c.Tiles.Length == 0)
            {
                Debug.LogError("[VampWolfs] farm_tiles.json não carregou: a fazenda vai sair vazia.");
                c = new FarmTileCatalog { Tiles = new FarmTileDef[0], Shapes = new FarmShapeDef[0] };
                return c;
            }
            c.loaded = true;
            return c;
        }

        public FarmShapeDef Shape(string type)
        {
            if (shapeMap == null)
            {
                shapeMap = new Dictionary<string, FarmShapeDef>();
                if (Shapes != null)
                {
                    foreach (FarmShapeDef s in Shapes) shapeMap[s.T] = s;
                }
            }
            FarmShapeDef shape;
            return type != null && shapeMap.TryGetValue(type, out shape) ? shape : null;
        }
    }
}
